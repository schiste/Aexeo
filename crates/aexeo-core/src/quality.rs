    /// Regression: macOS writes `._<name>` AppleDouble resource forks beside
    /// real files on a non-HFS volume, and the sidecar keeps the `.rs`
    /// extension. The source scan read every `*.rs` it found, so one binary
    /// sidecar made `fs::read_to_string` fail and the error propagated out
    /// of `quality` — the gate aborted with "stream did not contain valid
    /// UTF-8" and reported nothing at all, on any checkout that had one.
    #[test]
    fn quality_skips_appledouble_sidecars_instead_of_failing() {
        let temp_dir = tempfile::tempdir().unwrap();
        let root = temp_dir.path();
        write_quality_fixture_root(root);
        write_fixture_file(root, "crates/aexeo-core/src/lib.rs", "// source\n");

        // A real unwrap violation, so the scan has actual work to do.
        write_fixture_file(
            root,
            "crates/aexeo-core/src/rules.rs",
            "pub fn value() -> u8 {\n    Some(1).unwrap()\n}\n",
        );
        // The AppleDouble sidecar for that same file: binary, `.rs` named.
        // Bytes 0x00-0xFF in sequence, which is not valid UTF-8.
        let sidecar: Vec<u8> = (0u8..=255).collect();
        let sidecar_path = root.join("crates/aexeo-core/src/._rules.rs");
        fs::write(sidecar_path, &sidecar).unwrap();
        let cli_reference =
            "# CLI Reference\n\n<!-- Generated by aexeo-cli docs generate. Do not edit by hand. -->\n"
                .to_string();
        write_reference_documents(root, cli_reference.clone()).unwrap();

        // The point of the regression: this must not return an error.
        let findings = run_repo_quality_checks(root, &cli_reference).unwrap();

        // And the scan must still have run, not silently no-op'd.
        assert!(
            findings.iter().any(|finding| finding.rule_id == "QLT019"),
            "expected the real unwrap finding to still be reported; got {findings:?}"
        );
    }

