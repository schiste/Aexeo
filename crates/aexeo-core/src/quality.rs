    /// Regression: six config keys shipped for a long time as documented,
    /// loader-accepted, `config print`-rendered, and completely inert —
    /// `coverage_threshold`, `complexity_threshold`, `typecheck_command`,
    /// `enable_cache`, `cache_dir`, and `cache_ttl_seconds`. A user setting
    /// `enable_cache = false` changed nothing because there was no cache.
    /// QLT024 is the check that makes that class of rot loud.
    #[test]
    fn quality_reports_a_config_key_that_is_never_read() {
        let temp_dir = tempfile::tempdir().unwrap();
        let root = temp_dir.path();
        write_quality_fixture_root(root);
        // A config.rs declaring one key that is read elsewhere and one that
        // is only declared.
        write_fixture_file(
            root,
            "crates/aexeo-core/src/config.rs",
            "pub struct Config {\n    pub site_url: Option<String>,\n    pub orphan_exclude: Vec<String>,\n}\n",
        );
        // `site_url` is referenced in another module, so it is read.
        write_fixture_file(
            root,
            "crates/aexeo-core/src/policy.rs",
            "pub fn url(config: &Config) -> &str {\n    config.site_url.as_deref().unwrap_or(\"\")\n}\n",
        );
        let cli_reference =
            "# CLI Reference\n\n<!-- Generated by aexeo-cli docs generate. Do not edit by hand. -->\n"
                .to_string();
        write_reference_documents(root, cli_reference.clone()).unwrap();

        let findings = run_repo_quality_checks(root, &cli_reference).unwrap();

        let unread: Vec<&str> = findings
            .iter()
            .filter(|f| f.rule_id == "QLT024")
            .map(|f| f.message.as_str())
            .collect();
        assert_eq!(
            unread.len(),
            1,
            "expected exactly the unread key, got {unread:?}"
        );
        assert!(
            unread[0].contains("orphan_exclude"),
            "the reported key should be the unread one: {unread:?}"
        );
        // The read key must not be reported.
        assert!(
            !unread.iter().any(|m| m.contains("site_url")),
            "a key that is referenced elsewhere must not be reported: {unread:?}"
        );
    }

